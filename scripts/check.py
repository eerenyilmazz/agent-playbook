#!/usr/bin/env python3
"""Validate rule files and regenerate INDEX.md.

Checks: frontmatter fields, broken repo-relative links, token budgets.
Token count is estimated as chars / 4 (no network-dependent tokenizer).
Usage: python3 scripts/check.py            # check + write INDEX.md
       python3 scripts/check.py --no-write # check only (CI)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RULE_DIRS = ("company", "templates", "roles")
CHARS_PER_TOKEN = 4
ALWAYS_TOTAL_BUDGET = 2500   # leaves room inside the 5000-token prompt limit
ALWAYS_FILE_BUDGET = 400
TASK_FILE_BUDGET = 600
REQUIRED = {"scope", "owner", "status"}
LINK_RE = re.compile(r"\b((?:company|templates|roles)/[a-z0-9/-]+\.md)\b")


def tokens(text: str) -> int:
    return len(text) // CHARS_PER_TOKEN


def frontmatter(text: str) -> dict:
    match = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not match:
        return {}
    fields = {}
    for line in match.group(1).splitlines():
        key, _, value = line.partition(":")
        fields[key.strip()] = value.strip()
    return fields


def main() -> int:
    errors, rows, always_total = [], [], 0
    files = sorted(p for d in RULE_DIRS for p in (ROOT / d).rglob("*.md"))
    for path in files:
        rel = path.relative_to(ROOT).as_posix()
        text = path.read_text(encoding="utf-8")
        meta = frontmatter(text)
        count = tokens(text)

        missing = REQUIRED - meta.keys()
        if missing:
            errors.append(f"{rel}: missing frontmatter {sorted(missing)}")
        scope = meta.get("scope")
        if scope == "task" and not meta.get("when"):
            errors.append(f"{rel}: task file needs a 'when' line")

        budget = ALWAYS_FILE_BUDGET if scope == "always" else TASK_FILE_BUDGET
        if count > budget:
            errors.append(f"{rel}: ~{count} tokens > {budget}")
        if scope == "always":
            always_total += count

        for link in set(LINK_RE.findall(text)):
            if not (ROOT / link).is_file():
                errors.append(f"{rel}: broken link {link}")

        rows.append((rel, scope, meta.get("when", "every task"), meta.get("status", "?"), count))

    if always_total > ALWAYS_TOTAL_BUDGET:
        errors.append(f"always total ~{always_total} tokens > {ALWAYS_TOTAL_BUDGET}")

    if "--no-write" not in sys.argv:
        lines = [
            "# Index",
            "",
            "Generated by `scripts/check.py`. Load `always` files on every task;",
            "load a `task` file only when its trigger matches.",
            "",
            f"Always total: ~{always_total} tokens.",
            "",
            "| File | Scope | Load when | Status | ~Tokens |",
            "|---|---|---|---|---|",
        ]
        lines += [f"| {r} | {s} | {w} | {st} | {c} |" for r, s, w, st, c in rows]
        (ROOT / "INDEX.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    for err in errors:
        print("ERROR", err)
    print(f"{len(files)} files, always ~{always_total} tokens, {len(errors)} errors")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
